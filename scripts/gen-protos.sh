#!/usr/bin/env bash
# Regenerate Python stubs from proto/ into src/cdz/_proto (committed, so installs need no protoc).
# Needs grpcio-tools in the active interpreter: pip install grpcio-tools==1.68.1
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PY="${PYTHON:-python3}"
OUT="$ROOT/src/cdz/_proto"
rm -rf "$OUT"; mkdir -p "$OUT"
cd "$ROOT/proto"
mapfile -t PROTOS < <(find . -name '*.proto' | sed 's|^\./||' | sort)
# google/rpc/*.proto come from googleapis-common-protos (imported at runtime as google.rpc.*).
GAPI="$("$PY" -c 'import google.rpc, os; print(os.path.dirname(os.path.dirname(google.rpc.__path__[0])))')"
"$PY" -m grpc_tools.protoc -I. -I"$GAPI" --python_out="$OUT" --grpc_python_out="$OUT" "${PROTOS[@]}"
# protoc emits top-level packages (com.*, scalapb.*); re-root them under cdz._proto.
find "$OUT" -name '*.py' -print0 | xargs -0 sed -i -E 's/^from (com|scalapb)([. ])/from cdz._proto.\1\2/'
# grpc stubs for messages-only files are empty; drop them.
find "$OUT" -name '*_pb2_grpc.py' -print0 | while IFS= read -r -d '' f; do
  grep -q 'class .*Stub' "$f" || rm "$f"
done
find "$OUT" -type d -exec touch {}/__init__.py \;
echo "# Generated by scripts/gen-protos.sh from proto/ ($(cat "$ROOT/proto/VERSION")). Do not edit." > "$OUT/__init__.py"
echo "generated $(find "$OUT" -name '*_pb2*.py' | wc -l) modules into ${OUT#$ROOT/}"
